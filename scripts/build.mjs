import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const fromRoot = path => new URL("../" + path, import.meta.url);
const read = path => readFile(fromRoot(path), "utf8");

export const OUTPUT_HTML = "one-market-first.html";
// Tilda takes the game as three T123 (HTML code) blocks, pasted in this order.
export const OUTPUT_BLOCKS = {
  css: "01-t123-html-css.txt",
  engine: "02-t123-game-engine.txt",
  interface: "03-t123-game-interface.txt"
};

// Dependency order: a module may only import from modules listed before it.
// The engine block holds the first group, the interface block the second and last.
export const ENGINE_MODULES = ["hash", "tuning", "scenario", "rules", "clock", "storage"];
export const INTERFACE_MODULES = ["sync", "presentation", "host", "app"];
export const MODULES = [...ENGINE_MODULES, ...INTERFACE_MODULES];
const ENTRY = "app";
export const ENGINE_GLOBAL = "__omfEngine";

const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*['"]\.\/(\w+)\.mjs['"];?[ \t]*\n/gm;
const EXPORT = /^export\s+((?:async\s+)?(?:function\*?|const|let|class)\s+)(\w+)/gm;

// Each module becomes its own function scope: names cannot collide between modules,
// and every import is checked against the exports of an earlier module.
export function compileModules(sources) {
  const exported = new Map();
  const parts = {};
  for (const name of MODULES) {
    let body = sources[name];
    const needs = [];
    body = body.replace(IMPORT, (_, list, from) => {
      if (!exported.has(from)) throw new Error(`src/${name}.mjs imports ./${from}.mjs, which is unknown or comes later in MODULES.`);
      const names = list.split(",").map(item => item.trim()).filter(Boolean);
      for (const item of names) {
        if (!/^\w+$/.test(item)) throw new Error(`src/${name}.mjs: unsupported import specifier "${item}" (aliases are not supported).`);
        if (!exported.get(from).includes(item)) throw new Error(`src/${name}.mjs imports "${item}", which ./${from}.mjs does not export.`);
      }
      needs.push(`const { ${names.join(", ")} } = __omf_${from};`);
      return "";
    });
    const names = [];
    body = body.replace(EXPORT, (_, keyword, id) => { names.push(id); return keyword + id; });
    exported.set(name, names);
    const leftover = /^\s*(?:import\s*(?:[{*'"]|\w+\s+from\b)|export\s+(?:default\b|\{|\*|async\b|function\b|const\b|let\b|class\b|var\b))/m.exec(body);
    if (leftover) throw new Error(`src/${name}.mjs has an import/export form the build does not support: "${body.slice(leftover.index, leftover.index + 60).trim()}"`);
    const inner = [...needs, body.trim()].join("\n");
    parts[name] = name === ENTRY ? `// src/${name}.mjs\nawait (async () => {\n${inner}\n})();` :
      `// src/${name}.mjs\nconst __omf_${name} = (() => {\n${inner}\n${names.length ? `return { ${names.join(", ")} };` : ""}\n})();`;
  }
  return {parts, exported};
}

// All modules as one script body (used by tests and by anything that wants a single bundle).
export function inlineModules(sources) {
  const {parts} = compileModules(sources);
  return MODULES.map(name => parts[name]).join("\n\n");
}

const header = (number, title) => `<!-- T123 · Revolut — One Market First · block ${number} of 3: ${title} · generated by node scripts/build.mjs -->\n`;
const footer = "<!-- End T123 -->\n";

export async function build() {
  const sources = Object.fromEntries(await Promise.all(MODULES.map(async name => [name, await read("src/" + name + ".mjs")])));
  const [css, markup, cover] = await Promise.all([read("src/game.css"), read("src/template.html"), read("src/cover.svg")]);
  const {parts} = compileModules(sources);
  const part = name => parts[name].replace("<!-- COVER -->", cover.trim());

  const engineCode = ENGINE_MODULES.map(part).join("\n\n");
  const engineExports = ENGINE_MODULES.map(name => `${name}: __omf_${name}`).join(", ");
  const interfaceCode = INTERFACE_MODULES.map(part).join("\n\n");
  const imports = ENGINE_MODULES.map(name => `const __omf_${name} = engine.${name};`).join("\n");

  const blocks = {
    css: header(1, "HTML and styles") + "<style>\n" + css.trim() + "\n</style>\n\n" + markup.trim() + "\n" + footer,
    engine: header(2, "game engine") + '<script>\n(() => {\n"use strict";\n\n' + engineCode +
      `\n\nwindow.${ENGINE_GLOBAL} = { ${engineExports} };\n})();\n</script>\n` + footer,
    interface: header(3, "game interface") + '<script>\n(async () => {\n"use strict";\n\n' +
      `const engine = window.${ENGINE_GLOBAL};\n` +
      `if (!engine) {\n  const notice = document.querySelector('#one-market-first [data-ui="notice"]');\n` +
      `  if (notice) {\n    notice.textContent = "The game engine block is missing. Paste the three blocks in order: 1 HTML and styles, 2 game engine, 3 game interface.";\n    notice.hidden = false;\n  }\n  return;\n}\n` +
      imports + "\n\n" + interfaceCode + "\n})();\n</script>\n" + footer
  };

  for (const [name, text] of Object.entries(blocks)) {
    const scripts = text.slice(text.indexOf("<script>") + 8, text.lastIndexOf("</script>"));
    if (name !== "css" && /<\/script\s*>/i.test(scripts)) throw new Error(`The ${name} block contains a closing script tag.`);
  }

  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#f5efe3">
  <title>Revolut — One Market First</title>
  <style>html { background: #f5efe3; } body { margin: 0; }</style>
</head>
<body>
${blocks.css}${blocks.engine}${blocks.interface}</body>
</html>
`;
  return { html, blocks };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { html, blocks } = await build();
  await Promise.all([
    writeFile(fromRoot(OUTPUT_HTML), html, "utf8"),
    ...Object.entries(OUTPUT_BLOCKS).map(([key, path]) => writeFile(fromRoot(path), blocks[key], "utf8"))
  ]);
  for (const [key, path] of Object.entries(OUTPUT_BLOCKS)) console.log(path.padEnd(32), (Buffer.byteLength(blocks[key]) / 1024).toFixed(1) + " KB");
}
