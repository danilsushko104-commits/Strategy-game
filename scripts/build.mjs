import { readFile, writeFile } from 'node:fs/promises';

const fromRoot = path => new URL("../" + path, import.meta.url);
const read = path => readFile(fromRoot(path), "utf8");
const write = (path, content) => writeFile(fromRoot(path), content, "utf8");

const modules = ["scenario", "rules", "storage", "presentation", "host", "app"];
const sources = await Promise.all(modules.map(name => read("src/" + name + ".mjs")));
const [css, markup, cover] = await Promise.all([read("src/game.css"), read("src/template.html"), read("src/cover.svg")]);

// Tilda T123 takes one self-contained fragment. Keep the ES modules for local tests and maintenance.
const inlineScript = sources.map((source, index) => "// src/" + modules[index] + ".mjs\n" +
  source.replace(/^import \{[\s\S]*?\} from '\.\/\w+\.mjs';\n/gm, "").replace(/^export /gm, "").trim()
).join("\n\n").replace("<!-- COVER -->", cover.trim());

if (/<\/script\s*>/i.test(inlineScript) || /^\s*(import|export)\s+\{/m.test(inlineScript)) {
  throw new Error("The inlined script contains an unsupported module or closing tag.");
}

const fragment = '<!-- T123 · Revolut — One Market First · generated by node scripts/build.mjs -->\n<style>\n' +
  css.trim() + '\n</style>\n\n' + markup.trim() +
  '\n\n<script>\n(async () => {\n"use strict";\n\n' + inlineScript +
  '\n})();\n</script>\n<!-- End T123 -->\n';

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#f5efe3">
  <title>Revolut — One Market First</title>
  <style>html { background: #f5efe3; } body { margin: 0; }</style>
</head>
<body>
${fragment}</body>
</html>
`;

await Promise.all([write("pravo-na-vhod.html", html), write("pravo-na-vhod-t123.txt", fragment)]);
